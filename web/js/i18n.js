class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('wuwa_lang') || 'ar';
  }

  get lang() {
    return this.currentLang;
  }

  get t() {
    return translations[this.currentLang] || translations.ar;
  }

  toggle() {
    this.currentLang = this.currentLang === 'ar' ? 'en' : 'ar';
    localStorage.setItem('wuwa_lang', this.currentLang);
    this.apply();
    return this.currentLang;
  }

  apply() {
    const t = this.t;
    document.documentElement.lang = t.lang;
    document.documentElement.dir = t.dir;

    // Apply translations to all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (t[key]) {
        el.textContent = t[key];
      }
    });

    // Update switcher button label
    const switcher = document.getElementById('langSwitcher');
    if (switcher) {
      switcher.innerHTML = this.currentLang === 'ar' 
        ? `<span>العربية</span> <span style="opacity:0.4;">|</span> <span style="opacity:0.6;">EN</span>`
        : `<span>English</span> <span style="opacity:0.4;">|</span> <span style="opacity:0.6;">عربي</span>`;
    }
  }
}

export const i18n = new I18nManager();

